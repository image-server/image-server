// s3Server runs the full handler stack against a real S3-compatible store
// with credentialed reads and no ACLs, as for a private bucket
func s3Server(t *testing.T) (http.Handler, *core.ServerConfiguration, *S3Store) {
	t.Helper()
	store := NewS3Store(t)
	base := t.TempDir()
	sc := &core.ServerConfiguration{
		LocalBasePath:  base,
		RemoteBasePath: "images",
		DefaultQuality: 90,
		UploaderType:   "s3",
		AWSBucket:      store.Bucket,
		AWSRegion:      store.Region,
		AWSSkipACL:     true,
		S3Reads:        true,
	}
	sc.Adapters = &core.Adapters{Fetcher: &fetcherhttp.Fetcher{}, Paths: &paths.Paths{LocalBasePath: base, RemoteBasePath: "images"}}
	s3.Initialize(store.Bucket, store.Region, s3.Options{UsePathStyle: true, SkipACL: true})
	fetcher.Store = &s3.Uploader{}
	t.Cleanup(func() { fetcher.Store = nil })
	return server.NewHandler(sc, base), sc, store
}

func TestS3ReadsAfterLocalFilesExpire(t *testing.T) {
	h, sc, store := s3Server(t)

	data, err := os.ReadFile("../test/images/a.jpg")
	Ok(t, err)
	request, _ := http.NewRequest("POST", "/test_namespace?outputs=x200.jpg", bytes.NewReader(data))
	request.Header.Set("Content-Type", "image/jpeg")
	r := get2(h, request)
	Equals(t, http.StatusOK, r.Code)
	Matches(t, `"hash": "31e8b3187a9f63f26d58c88bf09a7bbd"`, r.Body.String())

	dir := "images/test_namespace/31e/8b3/187/a9f63f26d58c88bf09a7bbd/"
	keys := strings.Join(store.Keys(t, dir), ",")
	for _, name := range []string{"original", "info.json", "x200.jpg"} {
		Assert(t, strings.Contains(keys, dir+name), "%s not uploaded: %s", name, keys)
	}

	// The local copies expire; reads come back from the bucket
	Ok(t, os.RemoveAll(filepath.Join(sc.LocalBasePath, "test_namespace")))
	image := "/test_namespace/31e/8b3/187/a9f63f26d58c88bf09a7bbd/"
	for _, name := range []string{"x200.jpg", "original", "info.json", "c0.100_0.100_0.600_0.600-w100-q85.jpg"} {
		r := get(h, "GET", image+name)
		Equals(t, http.StatusOK, r.Code)
		Assert(t, r.Body.Len() > 10, "%s: empty body", name)
	}
	Equals(t, http.StatusNotFound, get(h, "GET", "/test_namespace/000/000/000/00000000000000000000000/w50.jpg").Code)

	// A variant generated by a read is uploaded in the background
	deadline := time.Now().Add(10 * time.Second)
	for store.Head(t, dir+"c0.100_0.100_0.600_0.600-w100-q85.jpg") == nil {
		Assert(t, time.Now().Before(deadline), "generated crop never uploaded")
		time.Sleep(50 * time.Millisecond)
	}
}

func get2(h http.Handler, request *http.Request) *httptest.ResponseRecorder {
	response := httptest.NewRecorder()
	h.ServeHTTP(response, request)
	return response
}
